import XCTest
@testable import PawmitCore

/// xita 연결: 하네스 hooks.d 파일, 이벤트 정규화, 작업 끝 답장, 터미널 없는 세션은 기다리지 않음
final class XitaTests: XCTestCase {
    let cli = "/Users/test/.pawmit/bin/pawmit"
    let home = URL(fileURLWithPath: "/Users/test")

    func target(config: PawmitConfig = PawmitConfig(), xitaHome: URL? = nil) -> HookInstaller.Target {
        HookInstaller.targets(config: config, cliPath: cli, home: home,
                              xitaHome: xitaHome ?? home.appendingPathComponent(".xita")).first { $0.agent == .xita }!
    }

    func envelope(_ event: String, _ payload: JSONValue) -> HookEnvelope {
        HookEnvelope(agent: "xita", event: event, expectsReply: true, pid: 1, ppid: 1, tty: nil, env: [:], cwd: "/tmp",
                     payload: payload, waitSeconds: 10)
    }

    func testHooksFileUsesOnlyKeysXitaAccepts() {
        let t = target()
        XCTAssertEqual(t.file.path, "/Users/test/.xita/harness/hooks.d/zz-pawmit.toml")
        XCTAssertEqual(t.format, .ownedFile)
        XCTAssertEqual(t.detectDir.path, "/Users/test/.xita")
        // xita kit.rs 는 deny_unknown_fields 라 키 하나만 틀려도 세션을 시작하지 않는다 → 내용을 통째로 고정한다
        XCTAssertEqual(t.ownedContent, """
        # Pawmit hooks for xita, generated by Pawmit. Remove with `pawmit uninstall xita`.
        # xita reads hooks.d in name order; the zz- prefix runs Pawmit's stop hook after other stop gates.

        [[hooks]]
        event = "session_start"
        command = ["/Users/test/.pawmit/bin/pawmit", "hook", "xita", "SessionStart"]
        timeout_secs = 10

        [[hooks]]
        event = "prompt"
        command = ["/Users/test/.pawmit/bin/pawmit", "hook", "xita", "UserPromptSubmit"]
        timeout_secs = 10

        [[hooks]]
        event = "notification"
        tools = ["permission_prompt"]
        command = ["/Users/test/.pawmit/bin/pawmit", "hook", "xita", "Notification"]
        timeout_secs = 10

        [[hooks]]
        event = "stop"
        command = ["/Users/test/.pawmit/bin/pawmit", "hook", "xita", "Stop"]
        timeout_secs = 600

        """)
    }

    func testStopTimeoutFollowsReplySetting() {
        var config = PawmitConfig()
        config.stopReplySeconds = 0
        XCTAssertTrue(target(config: config).ownedContent?.hasSuffix("\"Stop\"]\ntimeout_secs = 10\n") == true, "답장을 끄면 stop hook 도 짧게")
    }

    func testXitaHomeOverrideAndTomlEscaping() {
        let t = target(xitaHome: URL(fileURLWithPath: "/opt/xh"))
        XCTAssertEqual(t.file.path, "/opt/xh/harness/hooks.d/zz-pawmit.toml")
        XCTAssertEqual(HookInstaller.tomlString(#"a "b" \c"# + "\n\u{1}"), #""a \"b\" \\c\n\u0001""#)
        let spaced = HookInstaller.xitaHooksFile(cliPath: "/Users/t s/.pawmit/bin/pawmit", specs: [.init(event: "Stop", timeout: 5)])
        XCTAssertTrue(spaced.contains(#"command = ["/Users/t s/.pawmit/bin/pawmit", "hook", "xita", "Stop"]"#), "셸을 거치지 않는 argv 라 공백도 그대로")
    }

    func testInstallWritesAndUninstallRemovesOwnedFile() throws {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent("pawmit-xita-\(UUID().uuidString)")
        defer { try? FileManager.default.removeItem(at: root) }
        let xitaHome = root.appendingPathComponent(".xita")
        let t = target(xitaHome: xitaHome)
        XCTAssertEqual(HookInstaller.status(t, cliPath: cli), .agentMissing, "xita 폴더가 없으면 설치 안 됨")
        try FileManager.default.createDirectory(at: xitaHome, withIntermediateDirectories: true)
        XCTAssertEqual(HookInstaller.status(t, cliPath: cli), .notInstalled)

        try HookInstaller.execute(try HookInstaller.makePlan(t, install: true, cliPath: cli), backupDir: root.appendingPathComponent("backups"))
        XCTAssertEqual(try String(contentsOf: t.file, encoding: .utf8), t.ownedContent)
        XCTAssertEqual(HookInstaller.status(t, cliPath: cli), .installed)
        XCTAssertTrue(try HookInstaller.makePlan(t, install: true, cliPath: cli).isNoop, "두 번 설치해도 그대로")

        try HookInstaller.execute(try HookInstaller.makePlan(t, install: false, cliPath: cli), backupDir: root.appendingPathComponent("backups"))
        XCTAssertFalse(FileManager.default.fileExists(atPath: t.file.path))
        XCTAssertEqual(HookInstaller.status(t, cliPath: cli), .notInstalled)
    }

    /// xita stop 훅 payload (xita-harness kit.rs `on_stop`) 그대로
    func testStopReplyBlocksWithReason() {
        let env = envelope("Stop", ["event": "stop", "hook_event_name": "Stop", "session_id": "s-1", "session_dir": "/Users/test/.xita/sessions/s-1",
                                    "stop_hook_active": false, "last_assistant_message": "끝냈어요", "cwd": "/Users/test/work/app"])
        let e = AgentAdapters.normalize(env)
        XCTAssertEqual(e.agent, .xita)
        XCTAssertEqual(e.kind, .stop)
        XCTAssertEqual(e.message, "끝냈어요")
        XCTAssertEqual(e.sessionID, "s-1")
        XCTAssertEqual(e.projectName, "app")
        XCTAssertTrue(e.capabilities.contains(.reply))

        let out = AgentAdapters.render(HookReply(id: env.id, decision: .reply, message: "테스트도 돌려줘"), envelope: env).flatMap { JSONValue.parse($0) }
        XCTAssertEqual(out?["decision"]?.string, "block")
        XCTAssertEqual(out?["reason"]?.string, "테스트도 돌려줘")
        XCTAssertNil(AgentAdapters.render(HookReply(id: env.id, decision: .pass), envelope: env), "넘기면 출력 없음 → xita 는 그대로 턴을 닫는다")
    }

    func testStopWaitsOnlyWithTerminal() {
        let payload: JSONValue = ["hook_event_name": "Stop"]
        XCTAssertTrue(AgentAdapters.isInteractiveCandidate(agent: .xita, event: "Stop", payload: payload, hasTerminal: true))
        XCTAssertFalse(AgentAdapters.isInteractiveCandidate(agent: .xita, event: "Stop", payload: payload, hasTerminal: false),
                       "데몬 세션(웹·데스크탑 채팅)은 답장을 기다리지 않는다")
        XCTAssertTrue(AgentAdapters.isInteractiveCandidate(agent: .claude, event: "Stop", payload: payload, hasTerminal: false),
                      "다른 에이전트는 그대로")
        XCTAssertFalse(AgentAdapters.isInteractiveCandidate(agent: .xita, event: "Notification", payload: payload))
    }

    /// xita 승인 대기 알림 payload (xita-harness lib.rs `permission_prompt`)
    func testPermissionNotificationShowsToolAndSummary() {
        let env = envelope("Notification", ["event": "notification", "hook_event_name": "Notification", "session_id": "s-1",
                                            "notification_type": "permission_prompt", "message": "xita needs your permission to use shell",
                                            "tool": "shell", "summary": "$ cargo test", "cwd": "/Users/test/work/app"])
        let e = AgentAdapters.normalize(env)
        XCTAssertEqual(e.kind, .notification)
        XCTAssertEqual(e.notificationType, "permission_prompt")
        XCTAssertEqual(e.toolName, "shell")
        XCTAssertEqual(e.message, L10n.t("도구 실행 승인을 기다리고 있어요") + "\nshell · $ cargo test")
        XCTAssertNil(AgentAdapters.render(HookReply(id: env.id, decision: .pass), envelope: env))
    }

    func testStatusEvents() {
        XCTAssertEqual(AgentKind(loose: "xita"), .xita)
        XCTAssertEqual(AgentAdapters.normalize(envelope("SessionStart", ["hook_event_name": "SessionStart", "source": "startup"])).kind, .sessionStart)
        let prompt = AgentAdapters.normalize(envelope("UserPromptSubmit", ["hook_event_name": "UserPromptSubmit", "prompt": "빌드해 줘"]))
        XCTAssertEqual(prompt.kind, .promptSubmit)
        XCTAssertEqual(prompt.message, "빌드해 줘")
    }
}
